export function getVerseHindi(v: Pick<Verse, "id">): VerseHindi | undefined {
  return versesHindi[v.id]
}

export function hasHindiPage(v: Pick<Verse, "id">): boolean {
  return v.id in versesHindi
}

/** A verse's page in the reader's language: the Hindi page when one exists, else the English one. */
export function verseHref(v: Pick<Verse, "id" | "chapter" | "verse">, lang: "en" | "hi"): string {
  return lang === "hi" && hasHindiPage(v) ? `/hi/quotes/${verseSlug(v)}` : `/quotes/${verseSlug(v)}`
}
