// Turns scripts/verse-art/drawings.mjs into one static SVG per verse in public/verse-art/ plus
// src/components/quote/verseArtLabels.ts, or prints an HTML contact sheet of every drawing.
// Not part of `npm run build`: run it by hand after changing a drawing.
//
//   node scripts/verse-art/build.mjs                 write the SVGs and labels
//   node scripts/verse-art/build.mjs --sheet [dark]  print a contact sheet to stdout
//
// The page pulls a drawing in with <use href="/verse-art/<id>.svg#art">, so the art costs no
// JavaScript and caches as a file. Colors are written as var(--color-*) inline styles: custom
// properties inherit into <use> content, so the drawing follows the page's theme.
import { mkdir, readdir, rm, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { art } from "./drawings.mjs"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..")
const SVG_DIR = path.join(ROOT, "public/verse-art")
const LABELS = path.join(ROOT, "src/components/quote/verseArtLabels.ts")

// Light-mode values, used only when a file is opened on its own outside the site.
const FALLBACK = {
  clay: "#b5233f",
  gold: "#c99a3e",
  saffron: "#9c4a1c",
  "line-strong": "#93794c",
  teal: "#3b2e6b",
  paper: "#fbeedf",
}

/** class="text-clay fill-gold" → style="color:var(--color-clay,…);fill:var(--color-gold,…)" */
function classesToStyle(markup) {
  return markup.replace(/\sclass="([^"]*)"/g, (_, classes) => {
    const rules = classes.split(/\s+/).map((c) => {
      if (c === "text-transparent") return "color:transparent"
      const m = /^(text|fill)-(.+)$/.exec(c)
      if (!m || !(m[2] in FALLBACK)) throw new Error(`Unknown class "${c}"`)
      return `${m[1] === "text" ? "color" : "fill"}:var(--color-${m[2]},${FALLBACK[m[2]]})`
    })
    return ` style="${rules.join(";")}"`
  })
}

function minify(markup) {
  return markup.replace(/\s*\n\s*/g, "").replace(/>\s+</g, "><")
}

async function writeAssets() {
  await mkdir(SVG_DIR, { recursive: true })
  for (const file of await readdir(SVG_DIR)) {
    if (file.endsWith(".svg")) await rm(path.join(SVG_DIR, file))
  }
  for (const [id, { svg }] of Object.entries(art)) {
    const body = minify(classesToStyle(svg))
    const file = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 240 240"><g id="art" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">${body}</g></svg>\n`
    await writeFile(path.join(SVG_DIR, `${id}.svg`), file, "utf-8")
  }
  const labels = Object.entries(art)
    .map(([id, { label }]) => `  ${JSON.stringify(id)}: ${JSON.stringify(label)},`)
    .join("\n")
  await writeFile(
    LABELS,
    `// Generated by scripts/verse-art/build.mjs from scripts/verse-art/drawings.mjs. Don't edit by
// hand: change the drawing source and rerun the script. The drawings themselves are the
// matching files in public/verse-art/.

/** Accessible description of each verse's illustration, keyed by verse id. */
export const verseArtLabels: Record<string, string> = {
${labels}
}
`,
    "utf-8",
  )
  console.log(`Wrote ${Object.keys(art).length} drawings to public/verse-art/ and their labels`)
}

// Must match the ring VerseArt draws behind every illustration.
const RING = `<circle cx="120" cy="122" r="100" class="text-line-strong" opacity=".35" stroke-dasharray="2 6"/>`

function printSheet(dark) {
  const t = dark
    ? { paper: "#17120e", clay: "#e57d90", gold: "#e2bd6e", saffron: "#e5925e", line: "#8a7350", teal: "#a99be0", ink: "#cdb9a0" }
    : { paper: "#fbeedf", clay: "#b5233f", gold: "#c99a3e", saffron: "#9c4a1c", line: "#93794c", teal: "#3b2e6b", ink: "#675340" }
  const css = `body{margin:0;background:${t.paper};font:11px system-ui;color:${t.ink};display:grid;grid-template-columns:repeat(8,180px);gap:8px;padding:8px}
figure{margin:0;text-align:center}figcaption{height:28px;overflow:hidden}svg{width:180px;height:180px}
.text-clay{color:${t.clay}}.text-gold{color:${t.gold}}.text-saffron{color:${t.saffron}}.text-line-strong{color:${t.line}}
.text-teal{color:${t.teal}}.text-transparent{color:transparent}.fill-gold{fill:${t.gold}}.fill-clay{fill:${t.clay}}
.fill-teal{fill:${t.teal}}.fill-paper{fill:${t.paper}}.fill-line-strong{fill:${t.line}}`
  const cells = Object.entries(art).map(
    ([id, { label, svg }]) =>
      `<figure><svg viewBox="0 0 240 240" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">${RING}${svg}</svg><figcaption><b>${id}</b> ${label}</figcaption></figure>`,
  )
  console.log(`<!doctype html><meta charset="utf-8"><style>${css}</style>${cells.join("\n")}`)
}

// ---- --check: flag drawings that stray outside the safe circle -------------------------------

const SAFE = { cx: 120, cy: 122, r: 88 }

/** Sample points along a path's segments (M/L/H/V/Q/T/C/S, absolute or relative; arcs by endpoint). */
function samplePath(d) {
  const tokens = d.match(/[a-zA-Z]|-?\d*\.?\d+(?:e-?\d+)?/g) ?? []
  const pts = []
  let i = 0
  let cmd = ""
  let x = 0
  let y = 0
  let sx = 0
  let sy = 0
  let lastCtrl = null
  const num = () => parseFloat(tokens[i++])
  const quad = (x0, y0, x1, y1, x2, y2) => {
    for (let t = 0; t <= 1; t += 0.1) pts.push([(1 - t) ** 2 * x0 + 2 * t * (1 - t) * x1 + t * t * x2, (1 - t) ** 2 * y0 + 2 * t * (1 - t) * y1 + t * t * y2])
  }
  const cubic = (x0, y0, x1, y1, x2, y2, x3, y3) => {
    for (let t = 0; t <= 1; t += 0.1) {
      const u = 1 - t
      pts.push([u ** 3 * x0 + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t ** 3 * x3, u ** 3 * y0 + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t ** 3 * y3])
    }
  }
  while (i < tokens.length) {
    if (/[a-zA-Z]/.test(tokens[i])) cmd = tokens[i++]
    const rel = cmd === cmd.toLowerCase()
    const ox = rel ? x : 0
    const oy = rel ? y : 0
    switch (cmd.toUpperCase()) {
      case "M": x = ox + num(); y = oy + num(); sx = x; sy = y; pts.push([x, y]); cmd = rel ? "l" : "L"; lastCtrl = null; break
      case "L": x = ox + num(); y = oy + num(); pts.push([x, y]); lastCtrl = null; break
      case "H": x = ox + num(); pts.push([x, y]); lastCtrl = null; break
      case "V": y = oy + num(); pts.push([x, y]); lastCtrl = null; break
      case "Q": { const x1 = ox + num(), y1 = oy + num(), x2 = ox + num(), y2 = oy + num(); quad(x, y, x1, y1, x2, y2); lastCtrl = [x1, y1]; x = x2; y = y2; break }
      case "T": { const x1 = lastCtrl ? 2 * x - lastCtrl[0] : x, y1 = lastCtrl ? 2 * y - lastCtrl[1] : y; const x2 = ox + num(), y2 = oy + num(); quad(x, y, x1, y1, x2, y2); lastCtrl = [x1, y1]; x = x2; y = y2; break }
      case "C": { const a = [ox + num(), oy + num(), ox + num(), oy + num(), ox + num(), oy + num()]; cubic(x, y, ...a); lastCtrl = [a[2], a[3]]; x = a[4]; y = a[5]; break }
      case "S": { const x1 = lastCtrl ? 2 * x - lastCtrl[0] : x, y1 = lastCtrl ? 2 * y - lastCtrl[1] : y; const a = [ox + num(), oy + num(), ox + num(), oy + num()]; cubic(x, y, x1, y1, ...a); lastCtrl = [a[0], a[1]]; x = a[2]; y = a[3]; break }
      case "A": { i += 5; x = ox + num(); y = oy + num(); pts.push([x, y]); lastCtrl = null; break }
      case "Z": x = sx; y = sy; lastCtrl = null; break
      default: i++
    }
  }
  return pts
}

function rotateAbout(pts, transform) {
  const m = /rotate\((-?[\d.]+)\s+(-?[\d.]+)\s+(-?[\d.]+)\)/.exec(transform ?? "")
  if (!m) return pts
  const [a, cx, cy] = [(parseFloat(m[1]) * Math.PI) / 180, parseFloat(m[2]), parseFloat(m[3])]
  return pts.map(([px, py]) => [cx + (px - cx) * Math.cos(a) - (py - cy) * Math.sin(a), cy + (px - cx) * Math.sin(a) + (py - cy) * Math.cos(a)])
}

function checkBounds() {
  let problems = 0
  for (const [id, { svg }] of Object.entries(art)) {
    let worst = 0
    for (const [, tag, attrs] of svg.matchAll(/<(path|circle|ellipse|rect)\b([^>]*)>/g)) {
      const get = (name) => new RegExp(`\\s${name}="([^"]*)"`).exec(attrs)?.[1]
      const n = (name) => parseFloat(get(name) ?? "0")
      let pts = []
      if (tag === "path") pts = samplePath(get("d") ?? "")
      else if (tag === "circle") pts = Array.from({ length: 16 }, (_, k) => [n("cx") + Math.cos((k * Math.PI) / 8) * n("r"), n("cy") + Math.sin((k * Math.PI) / 8) * n("r")])
      else if (tag === "ellipse") pts = Array.from({ length: 16 }, (_, k) => [n("cx") + Math.cos((k * Math.PI) / 8) * n("rx"), n("cy") + Math.sin((k * Math.PI) / 8) * n("ry")])
      else pts = [[n("x"), n("y")], [n("x") + n("width"), n("y")], [n("x"), n("y") + n("height")], [n("x") + n("width"), n("y") + n("height")]]
      for (const [px, py] of rotateAbout(pts, get("transform"))) worst = Math.max(worst, Math.hypot(px - SAFE.cx, py - SAFE.cy))
    }
    if (worst > SAFE.r) {
      problems++
      console.log(`${id.padEnd(6)} reaches r=${worst.toFixed(1)} (safe ${SAFE.r})`)
    }
  }
  console.log(problems ? `${problems} drawing(s) outside the safe circle` : "All drawings inside the safe circle")
  return problems
}

if (process.argv.includes("--sheet")) printSheet(process.argv.includes("dark"))
else if (process.argv.includes("--check")) process.exitCode = checkBounds() ? 1 : 0
else await writeAssets()
